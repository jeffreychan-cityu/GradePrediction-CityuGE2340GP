"""Refresh browser data from the existing fitted model and metrics; no model fitting."""
from pathlib import Path
import csv
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]
model_path = ROOT / 'outputs/regression_model.json'
model = json.loads(model_path.read_text(encoding='utf-8'))
with (ROOT / 'outputs/metrics.csv').open(encoding='utf-8', newline='') as f:
    metrics = list(csv.DictReader(f))
with (ROOT / 'outputs/train_descriptive_statistics.csv').open(encoding='utf-8', newline='') as f:
    stats = {row['']: row for row in csv.DictReader(f)}
bands = json.loads((ROOT / 'config/grade_bands.json').read_text(encoding='utf-8'))
with (ROOT / 'outputs/processed/train_raw.csv').open(encoding='utf-8', newline='') as f:
    training_grades = sorted(float(row['Grades']) for row in csv.DictReader(f))
features = model['features'] + [model['reference_feature']]
data = {
    'model': model,
    'gradeBands': bands,
    'trainingGrades': training_grades,
    'sourceSha256': hashlib.sha256(model_path.read_bytes()).hexdigest(),
    'metrics': {row['model']: {key: float(row[key]) for key in ('MAE', 'RMSE', 'R2')} for row in metrics if row['split'] == 'test'},
    'trainingRanges': {key: [float(stats['min'][key]), float(stats['max'][key])] for key in features},
}
(ROOT / 'app/demo/model-data.js').write_text('/* Generated by export_model.py from existing outputs. */\n' + 'globalThis.GE2340_DATA = ' + json.dumps(data, indent=2) + ';\n', encoding='utf-8')
print('Updated app/demo/model-data.js from existing model and metrics.')
